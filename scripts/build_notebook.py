md(r'''## 10. Reconstruct correlations and integrate large angles
$$C(x)=\sum_\ell\frac{2\ell+1}{4\pi}C_\ell P_\ell(x),\qquad S_{1/2}=\int_{-1}^{1/2}C(x)^2dx=\mathbf C^TK\mathbf C.$$
This is the spectrum-based statistic. The cut-sky map estimator later is different.''')
